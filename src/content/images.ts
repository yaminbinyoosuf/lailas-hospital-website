export type ImageId = keyof typeof images;

/* -------------------------------------------------------------------------- */
/* Processed photo files (generated by `npm run photos`)                      */
/* -------------------------------------------------------------------------- */

interface ManifestEntry {
  width: number;
  height: number;
  /** Tiny base64 WebP used for blur-up. */
  blur: string;
  widths: number[];
}

const manifest = manifestJson as Record<string, ManifestEntry>;

const files = import.meta.glob('../assets/photos/*.{avif,webp}', {
  eager: true,
  query: '?url',
  import: 'default',
}) as Record<string, string>;

const fileUrl = (id: string, width: number, ext: 'avif' | 'webp') =>
  files[`../assets/photos/${id}-${width}.${ext}`];

export interface ResolvedPhoto {
  width: number;
  height: number;
  blur: string;
  avifSrcSet: string;
  webpSrcSet: string;
  fallback: string;
}

/** Returns the processed photo for an id, or undefined if none exists yet. */
export function getPhoto(id: ImageId): ResolvedPhoto | undefined {
  const entry = manifest[id];
  if (!entry) return undefined;
  const set = (ext: 'avif' | 'webp') =>
    entry.widths
      .map((w) => (fileUrl(id, w, ext) ? `${fileUrl(id, w, ext)} ${w}w` : null))
      .filter(Boolean)
      .join(', ');
  const largest = entry.widths[entry.widths.length - 1];
  return {
    width: entry.width,
    height: entry.height,
    blur: entry.blur,
    avifSrcSet: set('avif'),
    webpSrcSet: set('webp'),
    fallback: fileUrl(id, largest, 'webp'),
  };
}
