/** "രാവിലെ 9:30", "ഉച്ചയ്ക്ക് 2:00", "വൈകിട്ട് 5:30", "രാത്രി 9:00" */
const timeMl = (hhmm: string) => {
  const [h, m] = hhmm.split(':').map(Number);
  const hr = h % 12 === 0 ? 12 : h % 12;
  const clock = `${hr}:${String(m).padStart(2, '0')}`;
  if (h === 0 || h === 24) return `രാത്രി 12:00`;
  if (h < 12) return `രാവിലെ ${clock}`;
  if (h < 16) return `ഉച്ചയ്ക്ക് ${clock}`;
  if (h < 20) return `വൈകിട്ട് ${clock}`;
  return `രാത്രി ${clock}`;
};

